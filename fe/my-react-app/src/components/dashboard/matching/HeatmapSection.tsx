import type { MatchingResult } from '../../../types/matching';
import { getHeatmapColor, getHeatmapTextColor, formatHeatmapLabel } from '../../../utils/heatmap';

interface HeatmapSectionProps {
  result: MatchingResult;
  selectedCell?: { rowIndex: number; colIndex: number } | null;
  onCellClick?: (rowIndex: number, colIndex: number, score: number, result: MatchingResult, cvKey?: string, jdKey?: string) => void;
}

export default function HeatmapSection({ result, selectedCell, onCellClick }: HeatmapSectionProps) {
  if (!result.alignment_matrix_raw || !result.alignment_matrix_masked || !result.heatmap_labels) return null;
  const { cv: cvLabels, jd: jdLabels } = result.heatmap_labels;
  const clickable = Boolean(onCellClick);

  // Extract view key from label generated by BE: "[XXXX] text.." -> "XXXX"
  const extractKey = (label: string): string => {
    const m = label.match(/^\[(\w+)\]/);
    return m ? m[1] : '';
  };

  const renderMatrix = (matrix: number[][]) => (
    <div className="heatmap-table" style={{ gridTemplateColumns: `repeat(${jdLabels.length}, 1fr)` }}>
      {matrix.map((row, i) =>
        row.map((val, j) => {
          const isSelected = selectedCell?.rowIndex === i && selectedCell?.colIndex === j;
          const className = [
            'heatmap-cell',
            clickable ? 'heatmap-cell-clickable' : '',
            isSelected ? 'heatmap-cell-selected' : '',
          ].filter(Boolean).join(' ');
          const title = clickable
            ? `CV: ${cvLabels[i]}\nJD: ${jdLabels[j]}\nScore: ${val.toFixed(4)}\nKey: ${extractKey(cvLabels[i])} vs ${extractKey(jdLabels[j])}\nBấm để xem chi tiết`
            : `CV: ${cvLabels[i]} \nJD: ${jdLabels[j]} \nScore: ${val.toFixed(4)}`;
          return (
            <div
              key={`${i}-${j}`}
              className={className}
              style={{ backgroundColor: getHeatmapColor(val), color: getHeatmapTextColor(val) }}
              title={title}
              {...(clickable && {
                onClick: () => onCellClick!(i, j, val, result, extractKey(cvLabels[i]), extractKey(jdLabels[j])),
                role: 'button',
                tabIndex: 0,
                'aria-label': `CV ${cvLabels[i]} vs JD ${jdLabels[j]}: ${val.toFixed(2)}`,
                onKeyDown: (e: React.KeyboardEvent<HTMLDivElement>) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    onCellClick!(i, j, val, result, extractKey(cvLabels[i]), extractKey(jdLabels[j]));
                  }
                },
              })}
            >
              {val.toFixed(2)}
            </div>
          );
        })
      )}
    </div>
  );

  return (
    <section className="heatmap-visual-container">
      <div className="heatmap-header-main">
        <h3>Alignment Matrix Visualizer</h3>
        {clickable && (
          <span className="heatmap-hint-text">💡 Bấm vào ô bất kỳ để xem chi tiết nội dung CV ↔ JD</span>
        )}
      </div>
      <div className="heatmap-grid-split">
        <div className="heatmap-box">
          <h4>Alignment matrix (learned) before masking</h4>
          <div className="heatmap-wrapper">
            <div className="heatmap-y-axis">
              {cvLabels.map((label, i) => (<div key={i} className="axis-label" title={label}>{formatHeatmapLabel(label)}</div>))}
            </div>
            <div className="heatmap-main-content">
              {renderMatrix(result.alignment_matrix_raw)}
              <div className="heatmap-x-axis" style={{ gridTemplateColumns: `repeat(${jdLabels.length}, 1fr)` }}>
                {jdLabels.map((label, j) => (<div key={j} className="axis-label-x" title={label}>{formatHeatmapLabel(label)}</div>))}
              </div>
            </div>
          </div>
        </div>
        <div className="heatmap-box">
          <h4>Alignment matrix (learned) after masking</h4>
          <div className="heatmap-wrapper">
            <div className="heatmap-y-axis">
              {cvLabels.map((label, i) => (<div key={i} className="axis-label" title={label}>{formatHeatmapLabel(label)}</div>))}
            </div>
            <div className="heatmap-main-content">
              {renderMatrix(result.alignment_matrix_masked)}
              <div className="heatmap-x-axis" style={{ gridTemplateColumns: `repeat(${jdLabels.length}, 1fr)` }}>
                {jdLabels.map((label, j) => (<div key={j} className="axis-label-x" title={label}>{formatHeatmapLabel(label)}</div>))}
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
